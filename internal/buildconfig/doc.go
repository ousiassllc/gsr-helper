// だけを置く。実行時のコードは含まない。
//
// 設定ファイルはリポジトリルートにありコンパイル対象にもならないため、壊れても
// 通常のテストでは検知できない。ここでは一時ディレクトリに最小のモジュールを作り、
// リポジトリルートの Makefile を実際に実行して挙動を固定する。
//
// ドキュメントも同じくコンパイル対象ではなく、仕様書のコードブロックが設定ファイルの
// 実体から乖離しても、改訂履歴の版番号が重複・逆順になっても通常のテストでは検知
// できない。設定ファイルを読んで検証するテストと性格が同じなため、同じパッケージに置く。
