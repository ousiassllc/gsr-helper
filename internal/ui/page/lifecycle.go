package page

// page の寿命を知らせる Msg を集める。長寿命の処理（journalctl -f のような
// ストリーム、監視の goroutine、開いたままのファイル）を持つ page が、いつ畳めば
// よいかを知るための通知である。

// DeactivateMsg は page が裏へ回ったことを知らせる。親がタブを切り替えるときに、
// **離れるタブへ**配る。
//
// 裏に回ったタブは描画されないため、ストリームを流し続けても誰も読まない。畳む
// 機会が無いと、タブを行き来するたびに購読が積み上がる。受け取った page は
// 長寿命の処理を止め、その後始末を tea.Cmd で返すこと（返した Cmd は親が流す）。
//
// **状態そのものは捨てないこと。** 同じタブへ戻ったときにスクロール位置や選択が
// 失われると、裏に回ったことが利用者に見えてしまう。畳むのは外へ伸びている処理
// （プロセス・goroutine・購読）だけである。
type DeactivateMsg struct{}

// ActivateMsg は page が前面に戻ったことを知らせる。親がタブを切り替えるときに、
// **移動先のタブへ**配る。DeactivateMsg で畳んだ処理を張り直すために使う。
//
// **起動時に選択されているタブ（Runners）はこれを受け取らない。** 親は切り替えの
// ときにだけ配るためである。長寿命の処理を持つ page（Logs / Doctor / Setup）は
// いずれも起動時の既定タブではないので、「ActivateMsg で張り、DeactivateMsg で
// 畳む」だけで釣り合う。**既定タブが長寿命の処理を持つようになったら、親の
// 初期化からも配る必要がある**（Issue #63）。
type ActivateMsg struct{}

// ShutdownMsg はアプリの終了を知らせる。親は**有効な全タブへ**配る。
//
// 親は各 page が返した後始末の Cmd を tea.Sequence で終了より前に流すため、
// **q / ctrl+c（キー経由の終了）では後始末がランタイムの停止より前に実行される**
// （tea.Batch では終了と競合する）。裏のタブも受け取るので、DeactivateMsg で畳み
// 損ねた処理をここで確実に閉じられる。
//
// **シグナル（SIGINT / SIGTERM）による終了では走らない。** bubbletea は Update を
// 通さずにランタイムを畳むため、この Msg はどの page にも届かない。したがって
// **プロセスが消えても壊れない後始末**（子プロセスの回収、書きかけのファイル）は
// この通知に依存させず、生成した側（exec / audit）が自分で保証すること。
//
// 後始末は速やかに返すこと。ここで待たされた時間はそのまま終了の遅れになる。
type ShutdownMsg struct{}
